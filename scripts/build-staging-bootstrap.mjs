// Builds supabase/staging/bootstrap.sql: the whole schema for a NEW, EMPTY Supabase project.
// The migration folder can't be replayed as it stands (early migrations collide), and two are skipped:
// one is superseded by the file after it, and one only makes a named person an admin.
// Policies are dropped before being created, so the last definition in history wins.
// Never run the output on the live project. Run with: node scripts/build-staging-bootstrap.mjs
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const migrations = join(root, "supabase", "migrations");

const SKIP = new Map([
  ["20250825112128_18ceb381-be88-491f-a4ed-c65cf7712db4.sql", "superseded by 20250825112149, which defines the function it needs"],
  ["20250924053251_813979b0-460f-4da3-9ca3-65fedb3256ab.sql", "assigns admin to a named live account; see after_first_signup.sql"],
]);

const idempotentPolicies = (sql) =>
  sql.replace(/CREATE POLICY\s+("[^"]+")\s+ON\s+([\w."]+)/gi, 'DROP POLICY IF EXISTS $1 ON $2;\nCREATE POLICY $1 ON $2');

const parts = [
  "-- GENERATED by scripts/build-staging-bootstrap.mjs. Do not edit; do not run on the live project.",
  "-- Run once in the SQL editor of a new, empty Supabase project.",
];

for (const file of readdirSync(migrations).filter((name) => name.endsWith(".sql")).sort()) {
  if (SKIP.has(file)) {
    parts.push(`\n-- SKIPPED ${file}: ${SKIP.get(file)}`);
    continue;
  }
  parts.push(`\n-- ===== ${file} =====\n${idempotentPolicies(readFileSync(join(migrations, file), "utf8"))}`);
}

mkdirSync(join(root, "supabase", "staging"), { recursive: true });
writeFileSync(join(root, "supabase", "staging", "bootstrap.sql"), `${parts.join("\n")}\n`);
console.log("Wrote supabase/staging/bootstrap.sql");
